// Generates typed ABI modules from Foundry build output (contracts/out).
// Usage: pnpm abis   (run `forge build` first)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../../contracts/out");
const dest = join(here, "../src/abis");
const contracts = ["CardPriceOracle", "VaultEscrow", "VaultCardNFT", "VaultMarket", "SwapEscrow", "VaultSwap", "MockUSDC"];

mkdirSync(dest, { recursive: true });
const index = [];
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  const varName = name[0].toLowerCase() + name.slice(1) + "Abi";
  writeFileSync(
    join(dest, `${name}.ts`),
    `// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit.\nexport const ${varName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  index.push(`export { ${varName} } from "./${name}";`);
}
writeFileSync(join(dest, "index.ts"), index.join("\n") + "\n");
console.log(`Wrote ${contracts.length} ABIs to ${dest}`);
